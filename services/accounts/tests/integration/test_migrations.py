"""The accounts migrations against a real PostgreSQL (#3)."""

import asyncio

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine

ACCOUNTS_TABLES = {"users", "verification_tokens", "refresh_tokens", "outbox"}


async def _tables(url: str) -> dict[str, set[str]]:
    engine = create_async_engine(url)
    async with engine.connect() as conn:
        rows = await conn.execute(
            text(
                "SELECT schemaname, tablename FROM pg_tables "
                "WHERE schemaname IN ('accounts', 'public')"
            )
        )
        found: dict[str, set[str]] = {"accounts": set(), "public": set()}
        for schema, table in rows:
            found[schema].add(table)
    await engine.dispose()
    return found


def test_migrations_create_the_tables_in_the_accounts_schema(database_url: str) -> None:
    tables = asyncio.run(_tables(database_url))

    assert tables["accounts"] == ACCOUNTS_TABLES | {"alembic_version"}
    assert tables["public"] == set()


def test_tables_py_and_the_migrations_agree(alembic_config: Config) -> None:
    """Fails if someone changes tables.py without generating a migration."""
    try:
        command.check(alembic_config)
    except AutogenerateDiffsDetected as diffs:
        pytest.fail(f"tables.py has changes with no migration: {diffs}")


def test_migrations_can_be_undone_and_redone(database_url: str, alembic_config: Config) -> None:
    command.downgrade(alembic_config, "base")
    assert asyncio.run(_tables(database_url))["accounts"] == {"alembic_version"}

    command.upgrade(alembic_config, "head")
    assert asyncio.run(_tables(database_url))["accounts"] == ACCOUNTS_TABLES | {"alembic_version"}
